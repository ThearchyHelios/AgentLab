/** 一种分布（{键: 个数}）写成「通过 3 · 不通过 1」：叫法表里没有的键原样写 */
export function distText(dist: Record<string, number> | null | undefined, labels: Record<string, string>): string {
  const parts = Object.entries(dist ?? {}).filter(([, n]) => n > 0).map(([k, n]) => `${labels[k] ?? k} ${formatNumber(n)}`)
  return parts.length ? parts.join(' · ') : '—'
}
