/** 比率写成百分数：0.756 → 「75.6%」；没有分母（null）写「—」 */
export function pct(rate: number | null | undefined, digits = 1): string {
  if (rate == null || !Number.isFinite(rate)) return '—'
  const v = rate * 100
  return `${Number.isInteger(v) ? v : v.toFixed(digits)}%`
}

/** 「3 / 4 题通过（75%，95% 区间 30%–95%）」：数都是服务端的 stats.rate */
export function rateText(r: EvalRate | null | undefined, unit = '题'): string {
  if (!r || !r.n) return EVAL_TEXT.rate.none
  const ci = r.ci ? `，95% 区间 ${pct(r.ci[0], 0)}–${pct(r.ci[1], 0)}` : ''
  return `${formatNumber(r.passed)} / ${formatNumber(r.n)} ${unit}（${pct(r.rate)}${ci}）`
}

